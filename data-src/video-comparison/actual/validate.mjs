import assert from 'node:assert/strict';
import {readFile,writeFile,stat} from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {createHash} from 'node:crypto';
import {execFileSync} from 'node:child_process';
import ffmpeg from 'ffmpeg-static';
import ffprobe from 'ffprobe-static';

const source=path.dirname(fileURLToPath(import.meta.url));
const root=path.resolve(source,'../../..');
const cache=path.join(source,'.cache');
const output=path.join(root,'static/comparativa-videos/actual');
const shared=path.join(root,'static/comparativa-videos/shared');
const script=JSON.parse(await readFile(path.join(shared,'script.json'),'utf8'));
const audio=path.join(shared,script.audio);
const video=path.join(output,'video.mp4');
const probe=args=>JSON.parse(execFileSync(ffprobe.path,['-v','error',...args,'-of','json'],{cwd:source,encoding:'utf8',maxBuffer:8*1024*1024}));
const metadata=probe(['-count_frames','-show_streams','-show_format',video]);
const visual=metadata.streams.find(stream=>stream.codec_type==='video');
const sound=metadata.streams.find(stream=>stream.codec_type==='audio');
assert.equal(visual.width,1280);
assert.equal(visual.height,720);
assert.equal(visual.avg_frame_rate,'30/1');
assert.equal(Number(visual.nb_read_frames),1185);
assert.equal(Number(visual.duration),39.5);
assert.equal(visual.codec_name,'h264');
assert.equal(visual.pix_fmt,'yuv420p');
assert.ok(Math.abs(Number(metadata.format.duration)-39.5)<=0.15);
assert.equal(sound.codec_name,'mp3');
const sha256=buffer=>createHash('sha256').update(buffer).digest('hex');
assert.equal(sha256(await readFile(audio)),script.audioSha256);
const packetHashes=file=>probe(['-select_streams','a:0','-show_packets','-show_data_hash','sha256','-show_entries','packet=data_hash',file]).packets.map(packet=>packet.data_hash);
const originalPackets=packetHashes(audio);
const outputPackets=packetHashes(video);
assert.deepEqual(outputPackets,originalPackets);
const models=script.models;
const [lower,upper]=models[0].interval;
const probabilities=[models[0].height*(upper-lower),models[1].slope*(upper**2-lower**2)/2,models[2].heights[0]*(models[2].boundary-lower)+models[2].heights[1]*(upper-models[2].boundary)];
probabilities.forEach((value,index)=>assert.ok(Math.abs(value-models[index].probability)<1e-12));
const normalization=[models[0].height*2,models[1].slope*2,models[2].heights[0]+models[2].heights[1]];
normalization.forEach(value=>assert.equal(value,1));
const render=JSON.parse(await readFile(path.join(cache,'render.json'),'utf8'));
assert.deepEqual(render.errors,[]);
assert.deepEqual(render.externalRequests,[]);
assert.equal(render.encodedFrames,1185);
assert.ok(render.serverStopped);
assert.equal(render.formulaCount,16);
const samples=[];
for(const sample of render.samples) {
  const cue=script.cues[sample.cueIndex];
  assert.equal(sample.caption,cue.text);
  assert.equal(sample.measuredStart,cue.start);
  assert.equal(sample.measuredEnd,cue.end);
  assert.ok(sample.fontLoaded);
  assert.ok(sample.captionLines.length<=2);
  assert.ok(sample.captionBounds.y>=617 && sample.captionBounds.y+sample.captionBounds.height<=708);
  const frame=Math.round(sample.time*30);
  const decoded=path.join(cache,`decoded-${sample.cueIndex}.png`);
  execFileSync(ffmpeg,['-y','-v','error','-threads','1','-i',video,'-vf',`select=eq(n\\,${frame})`,'-frames:v','1','-threads','1',decoded],{cwd:source});
  const pixels=file=>execFileSync(ffmpeg,['-v','error','-threads','1','-i',file,'-frames:v','1','-f','rawvideo','-pix_fmt','rgb24','-threads','1','pipe:1'],{cwd:source,maxBuffer:4*1024*1024});
  const actual=pixels(decoded);
  const reference=pixels(path.join(cache,`reference-${sample.cueIndex}.png`));
  assert.equal(actual.length,1280*720*3);
  let difference=0;
  let captionDifference=0;
  let whiteCaptionPixels=0;
  let graphNonBackground=0;
  for(let index=0;index<actual.length;index+=3) {
    const pixel=index/3;
    const row=Math.floor(pixel/1280);
    const column=pixel%1280;
    const delta=Math.abs(actual[index]-reference[index])+Math.abs(actual[index+1]-reference[index+1])+Math.abs(actual[index+2]-reference[index+2]);
    difference+=delta;
    if(row>=604) {
      captionDifference+=delta;
      if(actual[index]>200 && actual[index+1]>200 && actual[index+2]>200)whiteCaptionPixels++;
    }
    if(row>=188 && row<464 && column>=128 && column<748 && actual[index+1]-actual[index]>12)graphNonBackground++;
  }
  const meanAbsoluteError=difference/actual.length;
  const captionMeanAbsoluteError=captionDifference/(1280*116*3);
  assert.ok(meanAbsoluteError<5,`Frame ${frame} differs from composition: ${meanAbsoluteError}`);
  assert.ok(captionMeanAbsoluteError<5,`Caption ${sample.cueIndex} differs: ${captionMeanAbsoluteError}`);
  assert.ok(whiteCaptionPixels>1500,`Caption ${sample.cueIndex} missing from decoded pixels`);
  assert.ok(graphNonBackground>5000,`Graph ${sample.cueIndex} blank`);
  samples.push({cue:sample.cueIndex,frame,time:frame/30,model:sample.model,probability:sample.probability,captionLines:sample.captionLines.length,whiteCaptionPixels,graphNonBackground,meanAbsoluteError,captionMeanAbsoluteError});
}
const html=await readFile(path.join(output,'player.html'),'utf8');
execFileSync(ffmpeg,['-y','-v','error','-threads','1','-i',video,'-vf','select=eq(n\\,918)','-frames:v','1','-threads','1',path.join(cache,'increasing-result-decoded.png')],{cwd:source});
assert.match(html,/<video\s[^>]*\bcontrols\b[^>]*\bplaysinline\b/);
assert.match(html,/poster="poster\.jpg"/);
assert.match(html,/<source src="video\.mp4" type="video\/mp4">/);
assert.match(html,/aspect-ratio:16\/9/);
assert.match(html,/@media\(max-width:600px\)/);
assert.doesNotMatch(html,/autoplay|https?:\/\/|<iframe|<script/i);
const ffmpegVersion=execFileSync(ffmpeg,['-version'],{cwd:source,encoding:'utf8'}).split('\n')[0];
const ffprobeVersion=execFileSync(ffprobe.path,['-version'],{cwd:source,encoding:'utf8'}).split('\n')[0];
const report={dimensions:[1280,720],fps:'30/1',frames:1185,videoDuration:visual.duration,containerDuration:metadata.format.duration,videoCodec:visual.codec_name,pixelFormat:visual.pix_fmt,profile:visual.profile,audioCodec:sound.codec_name,audioSampleRate:sound.sample_rate,audioChannels:sound.channels,audioPacketsUnaltered:outputPackets.length,sourceAudioSha256:script.audioSha256,videoSha256:sha256(await readFile(video)),videoBytes:(await stat(video)).size,posterBytes:(await stat(path.join(output,'poster.jpg'))).size,mathProbabilities:probabilities,normalization,versions:{...render.samples[0].versions,mathjax:'3.2.1',chromium:render.chromium,ffmpeg:ffmpegVersion,ffprobe:ffprobeVersion},samples,supplementalDecodedFrame:{frame:918,time:30.6,purpose:'Increasing model integral result 0.32'},playerStructureChecked:true,playerBrowserChecked:false,audioListened:false,renderErrors:render.errors,externalRequests:render.externalRequests,serverStopped:true};
await writeFile(path.join(source,'CHECKS.json'),JSON.stringify(report,null,2)+'\n');
